func TestBind(t *testing.T) {
	sql := `SELECT {{param.id}}::int, {{env.auth.tenantId}}, {{parent.id}}, {{param.id}}, '{{param.literal}}', "{{param.column}}", $$ {{param.dollar}} $$ /* {{param.comment}} /* nested */ */ -- {{param.line}}
`
	got, bindings, err := Bind(sql)
	if err != nil {
		t.Fatal(err)
	}
	if len(bindings) != 3 || bindings[1].Path != "auth.tenantId" {
		t.Fatalf("bindings: %+v", bindings)
	}
	if !strings.HasPrefix(got, `SELECT $1::int, $2, $3, $1, '{{param.literal}}'`) {
		t.Fatal(got)
	}
	for _, literal := range []string{`"{{param.column}}"`, `$$ {{param.dollar}} $$`, `/* {{param.comment}} /* nested */ */`, `-- {{param.line}}`} {
		if !strings.Contains(got, literal) {
			t.Fatalf("changed SQL literal %s", literal)
		}
	}
}
func TestBindRejectsInvalid(t *testing.T) {
	for _, sql := range []string{`SELECT {{unknown.x}}`, `SELECT {{param.x.y}}`, `SELECT {{param.id}`, `SELECT $1`, `SELECT 'oops`, `SELECT /* nope`, `SELECT $tag$ nope`, `SELECT {{param.bad-name}}`} {
		t.Run(sql, func(t *testing.T) {
			if _, _, err := Bind(sql); err == nil {
				t.Fatal("expected error")
			}
		})
	}
}
func TestRenderNested(t *testing.T) {
	child := &Query{Path: "Query.customer.customerItems", Field: "customerItems", Type: "CustomerItems", Func: "CustomerCustomerItems", SQLC: "SELECT sqlc.arg(param_id)", Columns: []Column{{"id", "Int"}}, Bindings: []Binding{{Source: "param", Path: "limit", Type: "Int"}}}
	root := &Query{Path: "Query.customer", Field: "customer", Type: "Customer", Func: "Customer", One: true, SQLC: "SELECT sqlc.arg(param_id)", Columns: []Column{{"id", "Int"}}, Bindings: []Binding{{Source: "param", Path: "id", Type: "Int"}}, Children: []*Query{child}}
	schema, sql, ops, err := Render([]*Query{root, child})
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"customer(id: Int!): Customer", "type CustomerItems", "customerItems(limit: Int!): [CustomerItems!]!"} {
		if !strings.Contains(schema, want) {
			t.Fatalf("missing %q in %s", want, schema)
		}
	}
	if !strings.Contains(sql, "-- name: CustomerCustomerItems :many") {
		t.Fatal(sql)
	}
	if !strings.Contains(ops["Customer.graphql"], "$Query_customer_customerItems_limit: Int!") {
		t.Fatal(ops)
	}
}

func TestBindSQLCPreservesSources(t *testing.T) {
	sql, bindings, err := BindSQLC(`SELECT {{param.id}}, {{env.auth.tenantId}}, {{parent.id}}, '{{param.id}}', {{param.id}}`)
	if err != nil {
		t.Fatal(err)
	}
	expected := `SELECT sqlc.arg(param_id), sqlc.arg(env_auth_tenantId), sqlc.arg(parent_id), '{{param.id}}', sqlc.arg(param_id)`
	if sql != expected || len(bindings) != 3 {
		t.Fatalf("%s; %+v", sql, bindings)
	}
}

// The compiler must only substitute value placeholders, not compose executable SQL.
func TestSQLIsEmittedAsWritten(t *testing.T) {
	source := "-- @many\n-- @batch parent.id=customerId\nSELECT customer_id AS \"customerId\", id FROM customer_items WHERE customer_id = ANY({{parent.id}}::int[]) ORDER BY id"
	normalized, _, err := BindSQLC(source)
	if err != nil {
		t.Fatal(err)
	}
	root := &Query{Path: "Query.customer", Field: "customer", Type: "Customer", Func: "Customer", One: true, SQLC: "SELECT 1 AS id", Columns: []Column{{"id", "Int"}}}
	child := &Query{Path: "Query.customer.items", Field: "items", Type: "Items", Func: "CustomerItems", Source: source, SQLC: normalized, Batch: map[string]string{"id": "customerId"}, Columns: []Column{{"customerId", "Int"}, {"id", "Int"}}}
	root.Children = []*Query{child}
	_, sql, _, err := Render([]*Query{root, child})
	if err != nil {
		t.Fatal(err)
	}
	expected := "-- Code generated by sqlgql. DO NOT EDIT.\n\n-- name: Customer :one\nSELECT 1 AS id;\n\n-- name: CustomerItems :many\n" + normalized + ";\n"
	if sql != expected {
		t.Fatalf("SQL was changed beyond parameter binding and sqlc comments:\n%s", sql)
	}
}

func TestPostgresTypeMappings(t *testing.T) {
	for oid, want := range map[uint32]string{20: "BigInt", 1016: "[BigInt]", 2950: "UUID", 114: "JSON", 3802: "JSON", 1000: "[Boolean]", 1005: "[Int]", 1007: "[Int]", 1021: "[Float]", 1022: "[Float]", 1009: "[String]", 1014: "[String]", 1015: "[String]", 2951: "[UUID]", 199: "[JSON]", 3807: "[JSON]"} {
		got, err := scalar(oid)
		if err != nil || got != want {
			t.Fatalf("%d => %q (%v), want %q", oid, got, err, want)
		}
	}
}

func TestConnectionOptIn(t *testing.T) {
	plain := &Query{Path: "Query.items", Field: "items", Type: "Items", Func: "Items", SQLC: "SELECT 1 AS id", Columns: []Column{{"id", "Int"}}}
	schema, _, _, err := Render([]*Query{plain})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(schema, "Connection") || strings.Contains(schema, "first:") {
		t.Fatal("plain @many changed")
	}
	plain.Connection = []string{"id"}
	schema, _, ops, err := Render([]*Query{plain})
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"first: Int", "after: String", "last: Int", "before: String", "ItemsConnection!", "type ItemsEdge", "type PageInfo"} {
		if !strings.Contains(schema, want) {
			t.Fatalf("missing %s", want)
		}
	}
	for _, want := range []string{"edges {", "node {", "cursor", "hasNextPage", "hasPreviousPage"} {
		if !strings.Contains(ops["Items.graphql"], want) {
			t.Fatal(ops)
		}
	}
	sql, _, err := BindSQLC("SELECT {{page.after.id}}::int, {{page.limit}}::int")
	if err != nil || sql != "SELECT sqlc.narg(page_after_id)::int, sqlc.arg(page_limit)::int" {
		t.Fatal(sql, err)
	}
}
